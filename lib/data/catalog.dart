// Catálogo base de la Pokédex Gómez.
// kind: mineral | ignea | sedimentaria | metamorfica
// rarity: 1 común · 2 poco común · 3 rara

class Mineral {
  final int n;
  final String id;
  final String name;
  final String kind;
  final String group;
  final String? formula;
  final double mohsMin;
  final double mohsMax;
  final String colors;
  final String luster; // brillo (minerales) o textura (rocas)
  final String? streak;
  final String? system;
  final int rarity;
  final int hex;
  final String fact;

  const Mineral({
    required this.n,
    required this.id,
    required this.name,
    required this.kind,
    required this.group,
    this.formula,
    required this.mohsMin,
    required this.mohsMax,
    required this.colors,
    required this.luster,
    this.streak,
    this.system,
    this.rarity = 1,
    required this.hex,
    required this.fact,
  });

  bool get isRock => kind != 'mineral';

  String get number => '#${n.toString().padLeft(3, '0')}';

  String get mohsText {
    String f(double v) => v == v.roundToDouble()
        ? v.toInt().toString()
        : v.toString().replaceAll('.', ',');
    return mohsMin == mohsMax ? f(mohsMin) : '${f(mohsMin)} – ${f(mohsMax)}';
  }
}

